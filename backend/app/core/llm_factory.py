class BaseLLMProvider:
    """Base interface for LLM providers."""

    def generate(self, prompt: str, system_prompt: Optional[str] = None, temperature: float = 0.2) -> str:
        raise NotImplementedError

    def is_available(self) -> bool:
        return True


class MockDeterministicLLMProvider(BaseLLMProvider):
    """Deterministic fallback LLM provider used when no API keys are configured or in tests."""

    def generate(self, prompt: str, system_prompt: Optional[str] = None, temperature: float = 0.2) -> str:
        # Check context in prompt to provide realistic grounded text
        prompt_lower = prompt.lower()
        if "punjabi" in prompt_lower or "alert" in prompt_lower or "ਚੇਤਾਵਨੀ" in prompt:
            return (
                "ਹੜ੍ਹ ਚੇਤਾਵਨੀ: ਪਿੰਡ ਵਾਸੀਆਂ ਨੂੰ ਸੂਚਿਤ ਕੀਤਾ ਜਾਂਦਾ ਹੈ ਕਿ ਦਰਿਆ ਵਿੱਚ ਪਾਣੀ ਦਾ ਪੱਧਰ ਵੱਧ ਰਿਹਾ ਹੈ। "
                "ਕਿਰਪਾ ਕਰਕੇ ਉੱਚੇ ਸਥਾਨਾਂ ਜਾਂ ਨਿਰਧਾਰਿਤ ਰਾਹਤ ਕੈਂਪ ਵਿੱਚ ਪਹੁੰਚੋ। ਐਮਰਜੈਂਸੀ ਹੈਲਪਲਾਈਨ 112 'ਤੇ ਸੰਪਰਕ ਕਰੋ।"
            )
