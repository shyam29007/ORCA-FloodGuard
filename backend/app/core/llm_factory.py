class GeminiLLMProvider(BaseLLMProvider):
    """Direct HTTPX-based Google Gemini provider without third-party library dependency."""

    def __init__(self, api_key: str, model_name: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model_name = model_name
        self.endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent"

    def is_available(self) -> bool:
        return bool(self.api_key and self.api_key.strip())

    def generate(self, prompt: str, system_prompt: Optional[str] = None, temperature: float = 0.2) -> str:
        if not self.is_available():
            logger.warning("GEMINI_API_KEY is not configured; using deterministic fallback provider.")
            return MockDeterministicLLMProvider().generate(prompt, system_prompt, temperature)

        contents = []
        if system_prompt:
            contents.append({"role": "user", "parts": [{"text": f"SYSTEM INSTRUCTION: {system_prompt}"}]})
            contents.append({"role": "model", "parts": [{"text": "Understood. I will strictly follow these instructions."}]})
        contents.append({"role": "user", "parts": [{"text": prompt}]})

        payload = {
            "contents": contents,
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": 1024,
            },
        }

        try:
            with httpx.Client(timeout=settings.REQUEST_TIMEOUT) as client:
                response = client.post(
                    f"{self.endpoint}?key={self.api_key}",
                    json=payload,
                    headers={"Content-Type": "application/json"},
                )
                if response.status_code == 200:
                    data = response.json()
                    candidates = data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        if parts:
                            return parts[0].get("text", "")
                    return "No output generated by Gemini."
                else:
                    logger.error("Gemini API error (%s): %s", response.status_code, response.text)
                    return MockDeterministicLLMProvider().generate(prompt, system_prompt, temperature)
        except Exception as e:
            logger.error("Failed to connect to Gemini API: %s; falling back to deterministic template.", str(e))
            return MockDeterministicLLMProvider().generate(prompt, system_prompt, temperature)


class OpenAILLMProvider(BaseLLMProvider):
    """OpenAI API provider."""

    def __init__(self, api_key: str, model_name: str = "gpt-4o-mini"):
        self.api_key = api_key
        self.model_name = model_name

    def is_available(self) -> bool:
        return bool(self.api_key and self.api_key.strip())

    def generate(self, prompt: str, system_prompt: Optional[str] = None, temperature: float = 0.2) -> str:
        if not self.is_available():
            return MockDeterministicLLMProvider().generate(prompt, system_prompt, temperature)

        messages = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append({"role": "user", "content": prompt})

        try:
            with httpx.Client(timeout=settings.REQUEST_TIMEOUT) as client:
                response = client.post(
                    "https://api.openai.com/v1/chat/completions",
                    headers={
                        "Authorization": f"Bearer {self.api_key}",
                        "Content-Type": "application/json",
                    },
                    json={
                        "model": self.model_name,
                        "messages": messages,
                        "temperature": temperature,
                    },
                )
                if response.status_code == 200:
                    return response.json()["choices"][0]["message"]["content"]
                logger.error("OpenAI API error (%s): %s", response.status_code, response.text)
                return MockDeterministicLLMProvider().generate(prompt, system_prompt, temperature)
        except Exception as e:
            logger.error("OpenAI request failed: %s; using deterministic fallback.", str(e))
            return MockDeterministicLLMProvider().generate(prompt, system_prompt, temperature)


_shared_llm_instance: Optional[BaseLLMProvider] = None


def get_llm() -> BaseLLMProvider:
    """Centralized LLM Factory instance getter."""
    global _shared_llm_instance
    if _shared_llm_instance is not None:
        return _shared_llm_instance

    provider_name = (settings.LLM_PROVIDER or "gemini").lower()
    logger.info("Initializing centralized LLM provider: %s (model: %s)", provider_name, settings.LLM_MODEL)

    if provider_name == "gemini":
        _shared_llm_instance = GeminiLLMProvider(
            api_key=settings.GEMINI_API_KEY or "",
            model_name=settings.LLM_MODEL or "gemini-1.5-flash",
        )
    elif provider_name == "openai":
        _shared_llm_instance = OpenAILLMProvider(
            api_key=settings.OPENAI_API_KEY or "",
            model_name=settings.LLM_MODEL or "gpt-4o-mini",
        )
    elif provider_name == "mock":
        _shared_llm_instance = MockDeterministicLLMProvider()
    else:
        logger.warning("Unknown LLM_PROVIDER '%s'. Defaulting to deterministic mock provider.", provider_name)
        _shared_llm_instance = MockDeterministicLLMProvider()

    return _shared_llm_instance

